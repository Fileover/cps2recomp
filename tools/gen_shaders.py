"""Compile the presenter (port/present.cpp)'s shaders (port/shaders/*.vert, *.frag; Vulkan GLSL 450 with SDL_GPU's resource
layout: vertex uniforms in set 1, fragment samplers in set 2, fragment uniforms in set 3) to SPIR-V with
glslangValidator and to Metal Shading Language with spirv-cross, and write port/shaders.inc; and the picture's
(video/gpu_picture.cpp: video/shaders/, which may #include their common.glsl) to video/picture_shaders.inc. Those files
are committed, so building the port needs neither tool.

  python3 tools/gen_shaders.py [--only port|video]
"""
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SETS = {"port": (ROOT / "port" / "shaders", ROOT / "port" / "shaders.inc"),
        "video": (ROOT / "video" / "shaders", ROOT / "video" / "picture_shaders.inc")}


def compile_stage(path, tmp):
    stage = path.suffix[1:]
    spv = Path(tmp) / (path.name + ".spv")
    r = subprocess.run(["glslangValidator", "-V", "-S", stage, "-I" + str(path.parent), "-o", str(spv), str(path)],
                       capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"{path.name}: glslang failed:\n{r.stdout}{r.stderr}")
    msl = subprocess.run(["spirv-cross", "--msl", "--msl-version", "20100", "--msl-decoration-binding", str(spv)],
                         capture_output=True, text=True)
    if msl.returncode != 0:
        sys.exit(f"{path.name}: spirv-cross failed:\n{msl.stderr}")
    return spv.read_bytes(), msl.stdout


def write(sources, output):
    out = ["// SPDX-License-Identifier: GPL-3.0-only",
           "// Copyright (C) 2026 Tommy McLeroy. Part of cps2recomp.",
           "// Generated by tools/gen_shaders.py from %s/. Do not edit." % sources.relative_to(ROOT), ""]
    with tempfile.TemporaryDirectory() as tmp:
        for path in sorted(sources.iterdir()):
            if path.suffix not in (".vert", ".frag"):
                continue
            name = path.stem + "_" + path.suffix[1:]
            spv, msl = compile_stage(path, tmp)
            data = ", ".join(f"0x{b:02x}" for b in spv)
            out.append(f"constexpr unsigned char k_{name}_spirv[] = {{{data}}};")
            lines = msl.replace("\\", "\\\\").replace('"', '\\"').split("\n")
            out.append(f"constexpr const char k_{name}_msl[] =")
            out.extend(f'    "{line}\\n"' for line in lines)
            out[-1] += ";"
            out.append("")
    output.write_text("\n".join(out))
    print(f"wrote {output.relative_to(ROOT)}")


def main():
    only = sys.argv[sys.argv.index("--only") + 1] if "--only" in sys.argv else None
    for name, (sources, output) in SETS.items():
        if only in (None, name):
            write(sources, output)


if __name__ == "__main__":
    main()
